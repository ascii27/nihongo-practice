// Regenerate the JLPT grammar seed migration from db/seeds/jlpt-grammar.csv.
// Usage (from repo root): node db/seeds/gen-grammar-seed.mjs
// Source CSV: the owner's curated jlptsensei.com list (Google Sheet export).
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, resolve } from "node:path";

const here = dirname(fileURLToPath(import.meta.url));
const csvPath = resolve(here, "jlpt-grammar.csv");
const outPath = resolve(here, "../migrations/1783382400000_grammar_points_seed.sql");
const raw = readFileSync(csvPath, "utf8");

// Minimal RFC-4180-ish CSV parser: handles quoted fields with embedded commas
// and doubled "" quotes. Returns array of row arrays.
function parseCSV(text) {
  const rows = [];
  let row = [], field = "", inQ = false;
  for (let i = 0; i < text.length; i++) {
    const c = text[i];
    if (inQ) {
      if (c === '"') {
        if (text[i + 1] === '"') { field += '"'; i++; }
        else inQ = false;
      } else field += c;
    } else if (c === '"') inQ = true;
    else if (c === ",") { row.push(field); field = ""; }
    else if (c === "\n") { row.push(field); rows.push(row); row = []; field = ""; }
    else if (c === "\r") { /* skip */ }
    else field += c;
  }
  if (field.length || row.length) { row.push(field); rows.push(row); }
  return rows;
}

const rows = parseCSV(raw);
const sqlEsc = (s) => (s ?? "").trim().replace(/'/g, "''");

const values = [];
const seenSlug = new Set();
for (const r of rows) {
  const level = (r[0] ?? "").trim();
  if (!/^N[1-5]$/.test(level)) continue;          // skip blank/separator rows
  const num = parseInt((r[1] ?? "").trim(), 10);
  const title = (r[2] ?? "").trim();
  const romaji = (r[3] ?? "").trim();
  const meaning = (r[4] ?? "").trim();
  if (!Number.isInteger(num) || !title) continue;
  const slug = `${level.toLowerCase()}-${num}`;
  if (seenSlug.has(slug)) throw new Error(`dup slug ${slug}`);
  seenSlug.add(slug);
  values.push(
    `('${sqlEsc(level)}', ${num}, '${sqlEsc(title)}', ` +
    `${romaji ? `'${sqlEsc(romaji)}'` : "NULL"}, '${sqlEsc(meaning)}', ` +
    `'https://jlptsensei.com', '${slug}')`,
  );
}

const header = `-- 1783382400000_grammar_points_seed.sql
-- Seed the JLPT grammar catalog (${values.length} points, N5–N1).
-- Source: jlptsensei.com list, via the owner's curated Google Sheet.
-- Generated by db/seeds/gen-grammar-seed.mjs from db/seeds/jlpt-grammar.csv.
-- Idempotent: ON CONFLICT (slug) keeps existing rows so re-running is safe.

INSERT INTO grammar_points (jlpt_level, sort_order, title, romaji, meaning, source, slug) VALUES
`;
const body = values.join(",\n") + "\nON CONFLICT (slug) DO NOTHING;\n";
writeFileSync(outPath, header + body);
console.log(`wrote ${values.length} rows to ${outPath}`);
